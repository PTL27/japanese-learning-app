// Text-to-Speech với improved error handling và voice management
let voicesLoaded = false;
let availableVoices = [];

export const loadVoices = () => {
  if ('speechSynthesis' in window) {
    const updateVoices = () => {
      availableVoices = window.speechSynthesis.getVoices();
      voicesLoaded = availableVoices.length > 0;
      console.log('Voices loaded:', availableVoices.length);
    };

    // Initial load
    updateVoices();
    
    // Listen for voices changed event
    if (!voicesLoaded) {
      window.speechSynthesis.addEventListener('voiceschanged', updateVoices);
    }
  }
};

export const playTextToSpeech = async (text, language = 'ja-JP') => {
  if (!('speechSynthesis' in window)) {
    alert(`Phát âm: ${text} (Trình duyệt không hỗ trợ TTS)`);
    return;
  }

  try {
    // Stop any current speech
    window.speechSynthesis.cancel();
    
    // Wait a bit for cancel to complete
    await new Promise(resolve => setTimeout(resolve, 100));
    
    // Ensure voices are loaded
    if (!voicesLoaded) {
      await new Promise(resolve => {
        const checkVoices = () => {
          if (window.speechSynthesis.getVoices().length > 0) {
            availableVoices = window.speechSynthesis.getVoices();
            voicesLoaded = true;
            resolve();
          } else {
            setTimeout(checkVoices, 100);
          }
        };
        checkVoices();
      });
    }

    const utterance = new SpeechSynthesisUtterance(text);
    utterance.lang = language;
    utterance.rate = 0.7; // Slower for learning
    utterance.pitch = 1.0;
    utterance.volume = 0.9;
    
    // Find best Japanese voice
    const japaneseVoices = availableVoices.filter(voice => 
      voice.lang.includes('ja') || 
      voice.name.toLowerCase().includes('japanese') ||
      voice.name.toLowerCase().includes('japan')
    );
    
    if (japaneseVoices.length > 0) {
      // Prefer female voices for language learning
      const femaleVoice = japaneseVoices.find(v => 
        v.name.toLowerCase().includes('female') || 
        v.name.toLowerCase().includes('woman')
      );
      utterance.voice = femaleVoice || japaneseVoices[0];
    }
    
    // Error handling
    utterance.onerror = (event) => {
      console.error('TTS Error:', event.error);
      if (event.error === 'network') {
        alert(`Phát âm: ${text} (Lỗi mạng)`);
      } else if (event.error === 'not-allowed') {
        alert(`Phát âm: ${text} (Cần cấp quyền microphone)`);
      } else {
        alert(`Phát âm: ${text} (${event.error})`);
      }
    };

    utterance.onend = () => {
      console.log('TTS completed');
    };

    // Speak with retry logic
    const speak = () => {
      try {
        window.speechSynthesis.speak(utterance);
      } catch (error) {
        console.error('Speak error:', error);
        alert(`Phát âm: ${text} (Lỗi phát âm)`);
      }
    };

    speak();

  } catch (error) {
    console.error('TTS Error:', error);
    alert(`Phát âm: ${text} (Lỗi hệ thống)`);
  }
};

